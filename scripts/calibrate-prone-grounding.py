#!/usr/bin/env python3
"""Measure visible prone geometry on all skins and optionally update owned clearance profiles."""
from pathlib import Path
import argparse
import os
import math
import re
import subprocess

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--apply', action='store_true', help='Save measured mesh clearances in DefaultGame.ini')
args = parser.parse_args()
project = Path(__file__).resolve().parents[1]
engine = Path(os.environ.get('UE_ROOT', '/Users/Shared/Epic Games/UE_5.8'))
editor = engine / 'Engine/Binaries/Mac/UnrealEditor.app/Contents/MacOS/UnrealEditor'
log = project / 'Saved/Testing/prone-grounding-calibration.log'
log.parent.mkdir(parents=True, exist_ok=True)
with log.open('w') as output:
    result = subprocess.run([
        str(editor), str(project / 'RespawnAndRage.uproject'),
        '/Game/EclipseRecoil/Maps/L_Depot?ERFullArsenalTest?ERAlphaBots=1?EROmegaBots=0?ERBotMode=Target',
        '-game', '-nullrhi', '-nosound', '-unattended', '-NoSplash', '-stdout', '-FullStdOutLogOutput',
        '-ExecCmds=t.MaxFPS 60', '-ERWorldPoseProbe', '-ERWorldPoseExternal', '-ERWorldPoseProne',
        '-ERWorldPoseAllGallery', '-ERProneCalibration', '-ini:Engine:[SystemSettings]:r.MeshStreaming=0',
    ], stdout=output, stderr=subprocess.STDOUT, timeout=180)
text = log.read_text(errors='replace')
rows = re.findall(r'ER_PRONE_GEOMETRY sample=\d+ skin=(\d+) mesh=(\S+) floor=[-\d.]+ core=([-\d.]+) client=0', text)
complete = re.search(r'ER_WORLD_POSE_COMPLETE result=(?:PASS|FAIL) samples=20', text)
if result.returncode not in (0, 1) or not complete or len(rows) != 20 or {int(skin) for skin, _, _ in rows} != set(range(20)):
    raise SystemExit(f'Calibration incomplete; inspect {log}')
config = project / 'Config/DefaultGame.ini'
original = config.read_text()
section_pattern = r'(?m)^\[RespawnAndRage\.ProneGrounding\]\n[^\[]*'
previous = re.search(section_pattern, original)
old = {}
if previous:
    for line in previous.group().splitlines()[1:]:
        if '=' in line and not line.lstrip().startswith(';'):
            key, value = line.split('=', 1)
            old[key] = float(value)
profiles = {}
for skin, mesh, floor in rows:
    gap = float(floor)
    if not -30 < gap < 100:
        raise SystemExit(f'Unexpected geometry measurement for skin {skin}: {gap}')
    offset = math.ceil(max(0.0, old.get(mesh, 0.0) + 2.0 - gap) * 2) / 2
    if offset > 30:
        raise SystemExit(f'Clearance exceeds the runtime envelope for skin {skin}: {offset}')
    profiles[mesh] = max(profiles.get(mesh, 0.0), offset)
    print(f'skin={skin} floor={gap:.3f} offset={offset:.3f} mesh={mesh}')
section = '[RespawnAndRage.ProneGrounding]\n; Generated by scripts/calibrate-prone-grounding.py --apply from visible vertices.\n'
section += ''.join(f'{mesh}={offset:.3f}\n' for mesh, offset in sorted(profiles.items()))
updated = re.sub(section_pattern, lambda _: section+'\n', original) if previous else original.rstrip()+'\n\n'+section
if args.apply:
    backup = log.parent / 'prone-grounding-before.ini'
    if not backup.exists():
        backup.write_bytes(config.read_bytes())
    config.write_text(updated.rstrip()+'\n')
    print('ER_PRONE_GROUNDING_APPLIED', len(profiles), 'mesh profiles')
else:
    print('ER_PRONE_GROUNDING_MEASURED', len(profiles), 'mesh profiles; use --apply to save')
